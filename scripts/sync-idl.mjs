// Copy Anchor's generated IDLs + types (target/ is git-ignored) into packages/sdk/src/idl/.
// Run after `pnpm build:programs`.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";

const programs = { insuwork_bond: "InsuworkBond", insuwork_escrow: "InsuworkEscrow", insuwork_disputes: "InsuworkDisputes" };
mkdirSync("packages/sdk/src/idl", { recursive: true });
for (const [name, type] of Object.entries(programs)) {
  const types = readFileSync(`target/types/${name}.ts`, "utf8");
  const json = readFileSync(`target/idl/${name}.json`, "utf8");
  writeFileSync(
    `packages/sdk/src/idl/${name}.ts`,
    `// GENERATED by scripts/sync-idl.mjs from target/ — do not edit.\n${types}\nexport const IDL = ${json.trim()} as unknown as ${type};\n`,
  );
  console.log(`synced ${name}`);
}
